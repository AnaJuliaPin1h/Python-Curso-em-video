# Leia a largura e o comprimento de um terreno.
# Calcule a área do terreno.
# Mostre o resultado.

largura = float(input("Insira a largura em metros do terreno: "))
comprimento = float(input("Insira o comprimento em metros do terreno: "))

area = largura * comprimento

print("Área do terreno:", area, "m²")