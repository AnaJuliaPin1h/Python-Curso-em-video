# Operadores Aritméticos

# + (Adição)
# Usado para somar dois valores.
# Exemplo: 5 + 3 = 8

# - (Subtração)
# Usado para subtrair um valor do outro.
# Exemplo: 8 - 3 = 5

# * (Multiplicação)
# Usado para multiplicar valores.
# Exemplo: 4 * 2 = 8

# / (Divisão)
# Realiza a divisão entre dois números e sempre retorna um número decimal (float).
# Exemplo: 10 / 2 = 5.0

# ** (Potência)
# Usado para calcular potência.
# Exemplo: 2 ** 3 = 8
# Isso significa: 2 * 2 * 2

# Outro exemplo:
# 3 ** 4 = 81
# Isso significa: 3 * 3 * 3 * 3



# // (Divisão Inteira)
# Realiza a divisão e retorna apenas a parte inteira do resultado,
# descartando a parte decimal.

# Exemplo:
# 10 // 3 = 3



# % (Módulo ou Resto da Divisão)
# Retorna o resto da divisão entre dois números.

# Exemplo:
# 10 % 3 = 1
# porque 3 * 3 = 9 e sobra 1



# Programa para somar dois números digitados pelo usuário

# Criamos a variável n1 que recebe um número digitado pelo usuário
n1 = int(input("Digite o primeiro valor:\n"))

# Criamos a variável n2 que recebe outro número digitado
n2 = int(input("Digite o segundo valor:\n"))

# Criamos a variável soma que recebe o resultado da adição entre n1 e n2
soma = n1 + n2

# Exibimos o resultado da soma na tela
print("A soma vale: {}".format(soma))






